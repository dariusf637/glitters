<h2>1. Оператор</h2>
<p>Оператор: салон красоты Glitters.<br>Адрес: {$address}.<br>Телефон: {$phone}.</p>
<p>Полное наименование юридического лица или статус самозанятого, ИНН и ОГРН владелец добавляет в этот абзац.</p>
<h2>2. Какие данные мы получаем</h2>
<p>Через форму на сайте: имя, телефон, выбранная услуга и текст сообщения. Этих сведений достаточно, чтобы перезвонить и подтвердить визит. Адрес электронной почты и паспортные данные через форму не запрашиваются.</p>
<p>Технические данные сервера — IP-адрес в виде обезличенного счётчика защиты от спама — не сохраняются в заявке.</p>
<h2>3. Цели и основание</h2>
<p>Данные обрабатываются, чтобы ответить на заявку, согласовать время и оказать услугу салона. Основание — согласие, которое вы даёте отметкой в форме (статья 6 Федерального закона № 152-ФЗ «О персональных данных»).</p>
<h2>4. Онлайн-запись</h2>
<p>Кнопки «Записаться через Яндекс» и «Записаться через Dikidi» открывают сайты этих сервисов. С момента перехода обработка данных регулируется их документами. Glitters получает запись уже в выбранном сервисе.</p>
<h2>5. Срок хранения</h2>
<p>Заявка хранится, пока она нужна для записи и связи, и не дольше трёх лет, если более короткий срок не потребуется по вашей просьбе. Затем запись удаляется из административной части сайта.</p>
